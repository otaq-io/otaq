//! What Settings → About and its dialogs show about this copy of the app (d0071): the version and the commit it was
//! built from (`build.rs`), the OS and its architecture read once at run time, Otaq's own license and the
//! third-party notices, both built into the binary so nothing comes from the network.

use std::process::Command;
use std::sync::OnceLock;

use otaq_view::view_models::about::{self, Build};
use otaq_view::view_models::licenses::{self, Parsed};

/// Otaq's own license file.
pub const LICENSE: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../LICENSE"));
/// The third-party notices, generated by `scripts/licenses.sh`.
pub const NOTICES: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../THIRD-PARTY-LICENSES.md"
));

/// The notices file, read once.
pub fn notices() -> &'static Parsed {
    static PARSED: OnceLock<Parsed> = OnceLock::new();
    PARSED.get_or_init(|| licenses::parse(NOTICES))
}

/// This build on this machine, read once.
pub fn build() -> &'static Build {
    static BUILD: OnceLock<Build> = OnceLock::new();
    BUILD.get_or_init(|| Build {
        version: env!("CARGO_PKG_VERSION").to_owned(),
        commit: env!("BUILD_COMMIT").to_owned(),
        os: os_name(),
        arch: about::arch_name(std::env::consts::ARCH).to_owned(),
        release: crate::install_place::release(),
    })
}

/// The section's view.
pub fn view() -> about::View {
    let parsed = notices();
    about::view(build(), LICENSE, parsed.rust_count(), parsed.npm_count())
}

/// The OS with its version, as a bug report wants it: "macOS 26.0", "Windows 10.0.26100", "Ubuntu 26.04". Falls
/// back to the bare OS name when the version can't be read.
fn os_name() -> String {
    let version = if cfg!(target_os = "macos") {
        output("sw_vers", &["-productVersion"]).map(|v| format!("macOS {v}"))
    } else if cfg!(target_os = "windows") {
        // "Microsoft Windows [Version 10.0.26100.4652]".
        output("cmd", &["/C", "ver"]).and_then(|v| {
            let inner = v.split("Version ").nth(1)?.trim_end_matches(']').to_owned();
            Some(format!("Windows {inner}"))
        })
    } else {
        std::fs::read_to_string("/etc/os-release")
            .ok()
            .and_then(|text| os_release(&text))
    };
    version.unwrap_or_else(|| std::env::consts::OS.to_owned())
}

fn output(program: &str, args: &[&str]) -> Option<String> {
    let out = Command::new(program).args(args).output().ok()?;
    let text = String::from_utf8_lossy(&out.stdout).trim().to_owned();
    (out.status.success() && !text.is_empty()).then_some(text)
}

/// `NAME` and `VERSION_ID` of `/etc/os-release`: "Ubuntu 26.04".
fn os_release(text: &str) -> Option<String> {
    let field = |key: &str| {
        text.lines()
            .find_map(|l| l.strip_prefix(key)?.strip_prefix('='))
            .map(|v| v.trim_matches('"').to_owned())
    };
    let name = field("NAME")?;
    Some(match field("VERSION_ID") {
        Some(version) => format!("{name} {version}"),
        None => name,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_built_in_files_parse() {
        let parsed = notices();
        assert!(parsed.rust_count() > 100, "{}", parsed.rust_count());
        assert!(parsed.npm_count() > 0);
        assert!(
            parsed
                .rust
                .iter()
                .all(|g| !g.items.is_empty() && !g.texts.is_empty())
        );
        // Every bundled source is one the notices file names, so the two stay in step.
        for b in licenses::BUNDLED {
            if let Some(url) = b.source {
                assert!(NOTICES.contains(url), "{url}");
            }
        }
        assert!(view().copyright.starts_with("© 2026 "));
    }

    #[test]
    fn os_release_name_and_version() {
        let text = "PRETTY_NAME=\"Ubuntu 26.04 LTS\"\nNAME=\"Ubuntu\"\nVERSION_ID=\"26.04\"\n";
        assert_eq!(os_release(text).as_deref(), Some("Ubuntu 26.04"));
        assert_eq!(
            os_release("NAME=Arch Linux\n").as_deref(),
            Some("Arch Linux")
        );
        assert_eq!(os_release("ID=x\n"), None);
    }

    #[test]
    fn this_machine_has_an_os_and_arch() {
        let b = build();
        assert!(!b.os.is_empty() && !b.arch.is_empty() && !b.commit.is_empty());
        assert_eq!(b.version, env!("CARGO_PKG_VERSION"));
    }
}
